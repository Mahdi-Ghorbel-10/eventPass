# 5. ADD TIER (Organizer Studio - Add Ticket Tier & Ticket Capacity)
# ==============================================================================
@functions_framework.http
def add_tier(request):
    """
    Adds a new ticket tier to an existing event, including its initial ticket count (total_capacity),
    pricing in TND, badge, and description.

    Expected JSON Body:
      - event_id: (str, required) e.g. "ev-a83d" or "evt-gammarth-2026"
      - name: (str, required) e.g. "VIP Backstage Pass"
      - price_tnd: (float|int, required) e.g. 85.0
      - total_capacity: (int, required) e.g. 100 tickets
      - badge: (str, optional) e.g. "VIP Access"
      - description: (str, optional)
      - sort_order: (int, optional)
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    event_id = (data.get("event_id") or "").strip()
    name = (data.get("name") or "").strip()
    badge = (data.get("badge") or "").strip() or None
    description = (data.get("description") or "").strip()

    if not event_id or not name:
        return make_json_response({
            "error": "Missing required fields: 'event_id' and 'name' are mandatory."
        }, 400)

    try:
        price_tnd = round(float(data.get("price_tnd", 40.0)), 3)
        if price_tnd < 0:
            return make_json_response({"error": "'price_tnd' cannot be negative."}, 400)
    except (ValueError, TypeError):
        return make_json_response({"error": "Invalid 'price_tnd' numerical value."}, 400)

    try:
        total_capacity = int(data.get("total_capacity", 50))
        if total_capacity <= 0:
            return make_json_response({"error": "'total_capacity' must be at least 1 ticket."}, 400)
    except (ValueError, TypeError):
        return make_json_response({"error": "Invalid 'total_capacity' integer value."}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # 1. Verify event exists
            cur.execute("SELECT id, title FROM events WHERE id = %s;", (event_id,))
            event_row = cur.fetchone()
            if not event_row:
                return make_json_response({"error": f"Event '{event_id}' not found."}, 404)

            # 2. Get next sort_order if not provided
            sort_order = data.get("sort_order")
            if sort_order is None:
                cur.execute("SELECT COALESCE(MAX(sort_order), -1) + 1 AS next_order FROM ticket_tiers WHERE event_id = %s;", (event_id,))
                so_row = cur.fetchone()
                sort_order = so_row["next_order"] if so_row else 0

            # 3. Insert tier
            tier_id = f"tier-{os.urandom(4).hex()}"
            cur.execute("""
                INSERT INTO ticket_tiers (
                    id, event_id, name, badge, price_tnd, total_capacity, sold_count, description, sort_order
                ) VALUES (%s, %s, %s, %s, %s, %s, 0, %s, %s)
                RETURNING id, event_id, name, badge, price_tnd, total_capacity, sold_count, description, sort_order, created_at;
            """, (tier_id, event_id, name, badge, price_tnd, total_capacity, description, sort_order))
            new_tier = cur.fetchone()

            # 4. Compute updated event totals
            cur.execute("""
                SELECT COUNT(*) as total_tiers, COALESCE(SUM(total_capacity), 0) as total_event_capacity, COALESCE(SUM(sold_count), 0) as total_event_sold
                FROM ticket_tiers WHERE event_id = %s;
            """, (event_id,))
            totals = cur.fetchone()

            conn.commit()

            return make_json_response({
                "status": "TIER_ADDED",
                "message": f"Tier '{name}' created with {total_capacity} tickets at {price_tnd} TND.",
                "tier": {
                    "id": new_tier["id"],
                    "event_id": new_tier["event_id"],
                    "name": new_tier["name"],
                    "badge": new_tier["badge"],
                    "price_tnd": float(new_tier["price_tnd"]),
                    "total_capacity": new_tier["total_capacity"],
                    "sold_count": new_tier["sold_count"],
                    "remaining_tickets": new_tier["total_capacity"] - new_tier["sold_count"],
                    "description": new_tier["description"],
                    "sort_order": new_tier["sort_order"],
                    "created_at": str(new_tier["created_at"])
                },
                "event_totals": {
                    "event_id": event_id,
                    "event_title": event_row["title"],
                    "total_tiers": totals["total_tiers"],
                    "total_event_capacity": totals["total_event_capacity"],
                    "total_event_sold": totals["total_event_sold"]
                }
            }, 201)

    except Exception as e:
        logger.error(f"Error in add_tier: {e}")
        return make_json_response({"error": str(e)}, 500)


