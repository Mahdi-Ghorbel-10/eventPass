# 6. UPDATE TIER (Update Tier Name, Pricing, Badges, and Ticket Capacity)
# ==============================================================================
@functions_framework.http
def update_tier(request):
    """
    Updates an existing ticket tier's properties:
    - Ticket capacity / tickets count (total_capacity or add_tickets delta)
    - Pricing (price_tnd)
    - Tier name & badge
    - Description & sort_order

    Validation:
      The new ticket capacity CANNOT be set below already sold tickets (sold_count).

    Expected JSON Body:
      - tier_id: (str, required) e.g. "tier-1" or "tier-9b2f"
      - total_capacity: (int, optional) Absolute new capacity
      - add_tickets: (int, optional) Relative tickets to add/subtract (e.g. +50 or -10)
      - name: (str, optional)
      - price_tnd: (float|int, optional)
      - badge: (str, optional)
      - description: (str, optional)
      - sort_order: (int, optional)
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    tier_id = (data.get("tier_id") or "").strip()

    if not tier_id:
        return make_json_response({"error": "Missing required field: 'tier_id' is mandatory."}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # 1. Fetch current tier
            cur.execute("""
                SELECT tt.*, e.title as event_title 
                FROM ticket_tiers tt
                JOIN events e ON tt.event_id = e.id
                WHERE tt.id = %s;
            """, (tier_id,))
            current = cur.fetchone()

            if not current:
                return make_json_response({"error": f"Tier '{tier_id}' not found."}, 404)

            current_capacity = current["total_capacity"]
            current_sold = current["sold_count"]

            # Calculate new capacity
            new_capacity = current_capacity
            if "total_capacity" in data and data["total_capacity"] is not None:
                try:
                    new_capacity = int(data["total_capacity"])
                except (ValueError, TypeError):
                    return make_json_response({"error": "Invalid 'total_capacity' value."}, 400)
            elif "add_tickets" in data and data["add_tickets"] is not None:
                try:
                    delta = int(data["add_tickets"])
                    new_capacity = current_capacity + delta
                except (ValueError, TypeError):
                    return make_json_response({"error": "Invalid 'add_tickets' delta value."}, 400)

            # Safety check: Cannot reduce capacity below already sold tickets
            if new_capacity < current_sold:
                return make_json_response({
                    "error": f"Cannot set capacity to {new_capacity}. Already {current_sold} ticket(s) have been sold for this tier.",
                    "current_sold": current_sold,
                    "current_capacity": current_capacity,
                    "minimum_allowed_capacity": current_sold
                }, 400)

            # Prepare optional updates
            new_name = data.get("name", current["name"]).strip() if "name" in data else current["name"]
            new_badge = data.get("badge", current["badge"]) if "badge" in data else current["badge"]
            new_desc = data.get("description", current["description"]) if "description" in data else current["description"]
            new_sort_order = data.get("sort_order", current["sort_order"]) if "sort_order" in data else current["sort_order"]

            new_price = current["price_tnd"]
            if "price_tnd" in data and data["price_tnd"] is not None:
                try:
                    new_price = round(float(data["price_tnd"]), 3)
                    if new_price < 0:
                        return make_json_response({"error": "'price_tnd' cannot be negative."}, 400)
                except (ValueError, TypeError):
                    return make_json_response({"error": "Invalid 'price_tnd' numerical value."}, 400)

            # Update in DB
            cur.execute("""
                UPDATE ticket_tiers
                SET name = %s,
                    badge = %s,
                    price_tnd = %s,
                    total_capacity = %s,
                    description = %s,
                    sort_order = %s
                WHERE id = %s
                RETURNING id, event_id, name, badge, price_tnd, total_capacity, sold_count, description, sort_order;
            """, (new_name, new_badge, new_price, new_capacity, new_desc, new_sort_order, tier_id))
            updated = cur.fetchone()

            conn.commit()

            return make_json_response({
                "status": "TIER_UPDATED",
                "message": f"Tier '{updated['name']}' updated. Capacity: {current_capacity} -> {updated['total_capacity']} tickets ({updated['sold_count']} sold, {updated['total_capacity'] - updated['sold_count']} available).",
                "tier": {
                    "id": updated["id"],
                    "event_id": updated["event_id"],
                    "event_title": current["event_title"],
                    "name": updated["name"],
                    "badge": updated["badge"],
                    "price_tnd": float(updated["price_tnd"]),
                    "total_capacity": updated["total_capacity"],
                    "sold_count": updated["sold_count"],
                    "remaining_tickets": updated["total_capacity"] - updated["sold_count"],
                    "description": updated["description"],
                    "capacity_change": {
                        "previous_capacity": current_capacity,
                        "new_capacity": updated["total_capacity"],
                        "delta": updated["total_capacity"] - current_capacity
                    }
                }
            }, 200)

    except Exception as e:
        logger.error(f"Error in update_tier: {e}")
        return make_json_response({"error": str(e)}, 500)


