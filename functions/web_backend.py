# 7. UPDATE TICKETS NUMBER (Dedicated Inventory & Capacity Adjuster by Tier)
# ==============================================================================
@functions_framework.http
def update_tickets_number(request):
    """
    Dedicated endpoint to adjust ticket capacity (stock count) for a specific ticket tier.
    Allows either setting an absolute ticket number or adding/subtracting tickets (e.g. +50 tickets).

    Expected JSON Body:
      - tier_id: (str, required) e.g. "tier-1"
      - total_capacity: (int, optional) Absolute new ticket inventory
      - add_tickets: (int, optional) Relative ticket delta (e.g. +50 tickets, -10 tickets)
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    tier_id = (data.get("tier_id") or "").strip()

    if not tier_id:
        return make_json_response({"error": "Missing required field: 'tier_id' is mandatory."}, 400)

    if "total_capacity" not in data and "add_tickets" not in data:
        return make_json_response({
            "error": "Either 'total_capacity' (absolute count) or 'add_tickets' (relative delta) must be provided."
        }, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute("""
                SELECT tt.*, e.title as event_title 
                FROM ticket_tiers tt
                JOIN events e ON tt.event_id = e.id
                WHERE tt.id = %s;
            """, (tier_id,))
            current = cur.fetchone()

            if not current:
                return make_json_response({"error": f"Tier '{tier_id}' not found."}, 404)

            current_cap = current["total_capacity"]
            sold = current["sold_count"]

            if "total_capacity" in data and data["total_capacity"] is not None:
                try:
                    new_cap = int(data["total_capacity"])
                except (ValueError, TypeError):
                    return make_json_response({"error": "Invalid 'total_capacity' integer."}, 400)
            else:
                try:
                    new_cap = current_cap + int(data["add_tickets"])
                except (ValueError, TypeError):
                    return make_json_response({"error": "Invalid 'add_tickets' integer."}, 400)

            if new_cap < sold:
                return make_json_response({
                    "error": f"Cannot set ticket count to {new_cap}. Already {sold} tickets have been sold.",
                    "current_sold": sold,
                    "current_capacity": current_cap,
                    "minimum_allowed": sold
                }, 400)

            cur.execute("""
                UPDATE ticket_tiers
                SET total_capacity = %s
                WHERE id = %s
                RETURNING id, name, price_tnd, total_capacity, sold_count;
            """, (new_cap, tier_id))
            updated = cur.fetchone()
            conn.commit()

            return make_json_response({
                "status": "TICKETS_NUMBER_UPDATED",
                "message": f"Ticket inventory for tier '{updated['name']}' updated to {new_cap} tickets.",
                "tier_id": updated["id"],
                "tier_name": updated["name"],
                "previous_capacity": current_cap,
                "new_capacity": updated["total_capacity"],
                "delta": updated["total_capacity"] - current_cap,
                "sold_count": updated["sold_count"],
                "remaining_tickets": updated["total_capacity"] - updated["sold_count"]
            }, 200)

    except Exception as e:
        logger.error(f"Error in update_tickets_number: {e}")
        return make_json_response({"error": str(e)}, 500)


