# 2. CREATE SELLER (Register Promoter Profile for Existing Event)
# ==============================================================================
@functions_framework.http
def create_seller(request):
    """
    Registers a new seller / campus ambassador account for an existing event.
    The seller can subsequently log in to the Seller POS app using their registered
    email and the event's 6-digit PIN code.

    Expected JSON Body:
      - event_id: (str, required) e.g. "ev-a83d" or "evt-gammarth-2026"
      - name: (str, required) e.g. "Yassine Ben Amor"
      - email: (str, required) e.g. "yassine@promoters.tn"
      - phone: (str, optional) e.g. "+216 22 456 789"
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    event_id = (data.get("event_id") or "").strip()
    name = (data.get("name") or "").strip()
    email = (data.get("email") or "").strip().lower()
    phone = (data.get("phone") or "").strip()

    if not event_id or not name or not email:
        return make_json_response({
            "error": "Missing required fields: 'event_id', 'name', and 'email' are mandatory."
        }, 400)

    # Basic email format check
    if "@" not in email or "." not in email:
        return make_json_response({"error": "Invalid email address format."}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # Verify event exists and retrieve title + PIN code
            cur.execute("SELECT id, title, venue, date, pin_code FROM events WHERE id = %s;", (event_id,))
            ev = cur.fetchone()
            if not ev:
                return make_json_response({"error": f"Event '{event_id}' not found."}, 404)

            seller_id = f"slr-{os.urandom(4).hex()}"

            cur.execute("""
                INSERT INTO sellers (id, event_id, name, email, phone, status)
                VALUES (%s, %s, %s, %s, %s, 'ACTIVE')
                ON CONFLICT (event_id, email) DO UPDATE
                SET name = EXCLUDED.name, phone = EXCLUDED.phone
                RETURNING id, name, email, phone, status, total_sales_count, total_sales_tnd, created_at;
            """, (seller_id, event_id, name, email, phone))

            row = cur.fetchone()
            conn.commit()

            return make_json_response({
                "status": "SELLER_CREATED",
                "message": "Seller profile registered successfully. Staff can now log in to POS mode.",
                "seller": {
                    "id": row["id"],
                    "event_id": event_id,
                    "event_title": ev["title"],
                    "name": row["name"],
                    "email": row["email"],
                    "phone": row["phone"],
                    "status": row["status"],
                    "total_sales_count": row["total_sales_count"],
                    "total_sales_tnd": float(row["total_sales_tnd"]),
                    "login_credentials": {
                        "email": row["email"],
                        "event_pin": ev["pin_code"],
                        "login_instructions": "Open the POS Cash Seller module, enter this registered email and the 6-digit event PIN to unlock cash ticketing."
                    }
                }
            }, 201)

    except Exception as e:
        logger.error(f"Error in create_seller: {e}")
        return make_json_response({"error": str(e)}, 500)


