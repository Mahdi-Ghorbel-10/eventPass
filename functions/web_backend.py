# 8. DELETE TIER (Organizer Studio - Safe Tier Deletion)
# ==============================================================================
@functions_framework.http
def delete_tier(request):
    """
    Deletes a ticket tier from an event.

    Safety Rules:
      1. Cannot delete a tier if tickets have already been sold or issued for it (sold_count > 0).
      2. Cannot delete the only remaining tier of an event (every event must have >= 1 tier).
      3. If 'force=true' is passed, will cascade delete only if no sold tickets exist.

    Expected JSON Body:
      - tier_id: (str, required) e.g. "tier-2"
      - force: (bool, optional, default False)
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    tier_id = (data.get("tier_id") or "").strip()
    force = bool(data.get("force", False))

    if not tier_id:
        return make_json_response({"error": "Missing required field: 'tier_id' is mandatory."}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # 1. Fetch tier
            cur.execute("""
                SELECT tt.*, e.title as event_title 
                FROM ticket_tiers tt
                JOIN events e ON tt.event_id = e.id
                WHERE tt.id = %s;
            """, (tier_id,))
            tier = cur.fetchone()

            if not tier:
                return make_json_response({"error": f"Tier '{tier_id}' not found."}, 404)

            event_id = tier["event_id"]

            # 2. Check if tickets have been sold
            if tier["sold_count"] > 0:
                return make_json_response({
                    "error": f"Cannot delete tier '{tier['name']}' because {tier['sold_count']} ticket(s) have already been sold. Reduce capacity or disable the tier instead of deleting.",
                    "sold_count": tier["sold_count"],
                    "tier_id": tier_id
                }, 409)

            # Check if any ticket rows reference this tier in tickets table
            cur.execute("SELECT COUNT(*) as ticket_count FROM tickets WHERE tier_id = %s;", (tier_id,))
            ticket_ref = cur.fetchone()
            if ticket_ref and ticket_ref["ticket_count"] > 0 and not force:
                return make_json_response({
                    "error": f"Cannot delete tier '{tier['name']}': {ticket_ref['ticket_count']} ticket records are associated with it in the tickets table.",
                    "ticket_count": ticket_ref["ticket_count"]
                }, 409)

            # 3. Check that event has at least one other tier
            cur.execute("SELECT COUNT(*) as tier_count FROM ticket_tiers WHERE event_id = %s;", (event_id,))
            count_row = cur.fetchone()
            if count_row and count_row["tier_count"] <= 1:
                return make_json_response({
                    "error": "Cannot delete the last remaining ticket tier. An event must always have at least one active ticket tier.",
                    "tier_count": count_row["tier_count"]
                }, 400)

            # 4. Delete the tier
            cur.execute("DELETE FROM ticket_tiers WHERE id = %s RETURNING id, name, event_id;", (tier_id,))
            deleted = cur.fetchone()

            # 5. Retrieve remaining tiers
            cur.execute("""
                SELECT id, name, badge, price_tnd, total_capacity, sold_count
                FROM ticket_tiers
                WHERE event_id = %s
                ORDER BY sort_order ASC;
            """, (event_id,))
            remaining_tiers = cur.fetchall()

            conn.commit()

            return make_json_response({
                "status": "TIER_DELETED",
                "message": f"Ticket tier '{tier['name']}' ({tier_id}) deleted successfully.",
                "deleted_tier": {
                    "id": tier["id"],
                    "name": tier["name"],
                    "event_id": tier["event_id"],
                    "event_title": tier["event_title"]
                },
                "remaining_tiers": [
                    {
                        "id": r["id"],
                        "name": r["name"],
                        "badge": r["badge"],
                        "price_tnd": float(r["price_tnd"]),
                        "total_capacity": r["total_capacity"],
                        "sold_count": r["sold_count"]
                    }
                    for r in remaining_tiers
                ]
            }, 200)

    except Exception as e:
        logger.error(f"Error in delete_tier: {e}")
        return make_json_response({"error": str(e)}, 500)

