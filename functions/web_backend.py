# 4. PAYMENT WEBHOOK (ClicToPay SMT, Konnect & Flouci Callback Listener)
# ==============================================================================
@functions_framework.http
def payment_webhook(request):
    """
    Called asynchronously by Tunisian Payment Processors when a customer completes payment:
    - ClicToPay (SMT getOrderStatus.do server-to-server check)
    - Konnect webhook callback with HMAC signature
    - Flouci developer webhook
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    payload = request.get_json(silent=True) or {}
    gateway = payload.get("gateway", "clictopay").lower()
    payment_ref = payload.get("payment_ref") or payload.get("order_id") or request.args.get("orderId")
    status = payload.get("status", "SUCCESS").upper()

    if not payment_ref:
        return make_json_response({"error": "Missing payment reference / order_id"}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # In production ClicToPay: verify getOrderStatus.do
            if gateway == "clictopay" and os.environ.get("CLICTOPAY_USER"):
                smt_url = "https://test.clictopay.com/payment/rest/getOrderStatus.do"
                resp = requests.get(smt_url, params={
                    "orderId": payment_ref,
                    "userName": os.environ.get("CLICTOPAY_USER"),
                    "password": os.environ.get("CLICTOPAY_PASSWORD")
                }, timeout=5)
                smt_data = resp.json()
                if smt_data.get("actionCode") != 0:
                    return make_json_response({"error": "ClicToPay payment declined by bank"}, 400)

            # Update ticket status to PAID and lock tier capacity
            cur.execute("""
                UPDATE tickets
                SET payment_status = 'PAID'
                WHERE payment_ref = %s OR id = %s
                RETURNING id, event_id, tier_id, buyer_name, buyer_email, ticket_hash;
            """, (payment_ref, payment_ref))
            ticket_row = cur.fetchone()

            if ticket_row:
                # Update tier sold count atomically
                cur.execute("""
                    UPDATE ticket_tiers
                    SET sold_count = sold_count + 1
                    WHERE id = %s AND sold_count < total_capacity;
                """, (ticket_row["tier_id"],))
                conn.commit()

                return make_json_response({
                    "status": "CONFIRMED",
                    "ticket_id": ticket_row["id"],
                    "qr_hash": ticket_row["ticket_hash"],
                    "email_dispatched_to": ticket_row["buyer_email"]
                }, 200)

            return make_json_response({"status": "ORDER_NOT_FOUND"}, 404)

    except Exception as e:
        logger.error(f"Error in payment_webhook: {e}")
        return make_json_response({"error": str(e)}, 500)


