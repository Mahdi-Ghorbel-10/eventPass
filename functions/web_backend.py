# 3. CREATE CHECKOUT SESSION (Web App Public Attendee Checkout)
# ==============================================================================
@functions_framework.http
def create_checkout(request):
    """
    Called by Web App attendee checkout form.
    Validates ticket tier availability, creates a pending reservation, and returns merchant payment URL.
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    tier_id = data.get("tier_id")
    event_slug = data.get("event_slug")
    buyer_name = data.get("buyer_name")
    buyer_email = data.get("buyer_email")
    buyer_phone = data.get("buyer_phone")
    payment_method = data.get("payment_method", "clictopay")

    if not tier_id or not buyer_name or not buyer_email or not buyer_phone:
        return make_json_response({"error": "Missing required buyer or tier fields"}, 400)

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # Check tier capacity
            cur.execute("""
                SELECT tt.id, tt.price_tnd, tt.total_capacity, tt.sold_count, tt.name as tier_name,
                       e.id as event_id, e.title, e.secret_key
                FROM ticket_tiers tt
                JOIN events e ON tt.event_id = e.id
                WHERE tt.id = %s;
            """, (tier_id,))
            tier = cur.fetchone()

            if not tier:
                return make_json_response({"error": "Ticket tier not found"}, 404)

            if tier["sold_count"] >= tier["total_capacity"]:
                return make_json_response({"error": "Tier sold out"}, 409)

            ticket_id = f"TKT-{os.urandom(3).hex().upper()}"
            ticket_hash = generate_ticket_hmac(ticket_id, tier["event_id"], tier["secret_key"])
            order_ref = f"ORD-{os.urandom(4).hex().upper()}"

            # Insert pending ticket reservation
            cur.execute("""
                INSERT INTO tickets 
                (id, event_id, tier_id, buyer_name, buyer_phone, buyer_email, price_paid_tnd, payment_method, payment_ref, payment_status, ticket_hash)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 'PENDING', %s);
            """, (
                ticket_id, tier["event_id"], tier["id"],
                buyer_name, buyer_phone, buyer_email,
                tier["price_tnd"], payment_method, order_ref, ticket_hash
            ))
            conn.commit()

            # Return gateway payment redirection URL
            redirect_url = f"https://api.eventpass.tn/pay/{payment_method}?ref={order_ref}&amount={tier['price_tnd']}"
            return make_json_response({
                "ticket_id": ticket_id,
                "order_ref": order_ref,
                "amount_tnd": float(tier["price_tnd"]),
                "redirect_url": redirect_url
            }, 201)

    except Exception as e:
        logger.error(f"Error in create_checkout: {e}")
        return make_json_response({"error": str(e)}, 500)


