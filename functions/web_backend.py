# 1. CREATE EVENT (Organizer Event & Multi-Tier Setup)
# ==============================================================================
@functions_framework.http
def create_event(request):
    """
    Creates a new event with multiple ticket tiers and enabled payment gateways (ClicToPay, Konnect, Flouci).
    Persists atomically to Cloud SQL PostgreSQL in a single ACID transaction.

    Security rule:
      The 6-digit gate PIN CANNOT be chosen or provided by the organizer.
      It is strictly generated by the backend using cryptographic randomness and returned in the response.

    Media rule:
      The banner is the lead (first) image of the cover photo gallery (cover_images[0]).

    Expected JSON Body:
      - title: (str, required) e.g. "Carthage Electronic Dunes 2026"
      - venue: (str, required) e.g. "Amphithéâtre Romain de Carthage"
      - city: (str, required) e.g. "Carthage, Tunis"
      - date: (str, required) e.g. "2026-10-15"
      - time: (str, required) e.g. "21:00 - 04:00"
      - subtitle: (str, optional)
      - slug: (str, optional, auto-generated from title if missing)
      - category: (str, optional, default "Festival")
      - cover_images: (list[str], optional) Photo gallery URLs. First photo is used as primary banner.
      - enabled_gateways: (list[str], optional, default ['CLICTOPAY', 'KONNECT', 'FLOUCI'])
      - organizer_id: (str, optional)
      - sellers: (list[dict], optional) List of promoter/seller accounts to provision at creation:
          - name: (str, required) e.g. "Amine Trabelsi"
          - email: (str, required) e.g. "amine@insat.tn"
          - phone: (str, optional) e.g. "+216 55 120 401"
      - tiers: (list[dict], required) List of ticket tiers:
          - name: (str, required) e.g. "Wave Pass", "VIP Backstage"
          - price_tnd: (float|int, required) e.g. 55.0
          - total_capacity: (int, required) e.g. 150
          - badge: (str, optional) e.g. "Bestseller", "VIP Access"
          - description: (str, optional)
    """
    if request.method == "OPTIONS":
        return make_json_response({}, 204)

    data = request.get_json(silent=True) or {}
    title = (data.get("title") or "").strip()
    venue = (data.get("venue") or "").strip()
    city = (data.get("city") or "Tunis").strip()
    date = (data.get("date") or "").strip()
    time = (data.get("time") or "21:00 - 04:00").strip()
    subtitle = data.get("subtitle") or ""
    category = data.get("category") or "Festival"
    cover_images = data.get("cover_images") or []
    organizer_id = data.get("organizer_id")
    raw_gateways = data.get("enabled_gateways")
    tiers = data.get("tiers") or []
    initial_sellers = data.get("sellers") or []

    if not title or not venue or not date:
        return make_json_response({
            "error": "Missing required fields: title, venue, and date are mandatory."
        }, 400)

    if not isinstance(tiers, list) or len(tiers) == 0:
        return make_json_response({
            "error": "At least one ticket tier must be provided in 'tiers'."
        }, 400)

    # Validate & normalize payment gateways
    valid_gateways = {"CLICTOPAY", "KONNECT", "FLOUCI"}
    if raw_gateways and isinstance(raw_gateways, list):
        enabled_gateways = [gw.upper() for gw in raw_gateways if gw.upper() in valid_gateways]
        if not enabled_gateways:
            enabled_gateways = ["CLICTOPAY", "KONNECT", "FLOUCI"]
    else:
        enabled_gateways = ["CLICTOPAY", "KONNECT", "FLOUCI"]

    # Generate unique slug if not provided
    slug = (data.get("slug") or "").strip().lower()
    if not slug:
        clean_slug = re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')
        slug = f"{clean_slug}-{os.urandom(2).hex()}"

    # Gate PIN cannot be supplied by the organizer - strictly minted by backend
    pin_code = f"{secrets.randbelow(900000) + 100000}"

    # Generate unique cryptographic HMAC secret for this event
    secret_key = os.urandom(24).hex()
    event_id = f"ev-{os.urandom(4).hex()}"

    # Banner is the primary image of the cover photos
    if isinstance(cover_images, list) and len(cover_images) > 0:
        banner_url = cover_images[0]
    else:
        default_photo = "https://images.unsplash.com/photo-1516450360452-9312f5e86fc7?auto=format&fit=crop&w=1200&q=80"
        cover_images = [default_photo]
        banner_url = default_photo

    try:
        conn = get_db_connection()
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            # 1. Insert Event record
            cur.execute("""
                INSERT INTO events (
                    id, organizer_id, title, subtitle, slug, category, date, time, venue, city,
                    banner_url, cover_images, pin_code, secret_key, enabled_gateways, status
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 'PUBLISHED');
            """, (
                event_id, organizer_id, title, subtitle, slug, category, date, time, venue, city,
                banner_url, cover_images, pin_code, secret_key, enabled_gateways
            ))

            # 2. Insert all Ticket Tiers atomically
            created_tiers = []
            for idx, tier in enumerate(tiers):
                tier_id = f"tier-{os.urandom(4).hex()}"
                tier_name = (tier.get("name") or f"Tier {idx + 1}").strip()
                try:
                    price_tnd = round(float(tier.get("price_tnd", 40.0)), 3)
                except (ValueError, TypeError):
                    price_tnd = 40.0

                try:
                    total_capacity = int(tier.get("total_capacity", 100))
                except (ValueError, TypeError):
                    total_capacity = 100

                badge = tier.get("badge")
                description = tier.get("description", "")

                cur.execute("""
                    INSERT INTO ticket_tiers (
                        id, event_id, name, badge, price_tnd, total_capacity, sold_count, description, sort_order
                    ) VALUES (%s, %s, %s, %s, %s, %s, 0, %s, %s);
                """, (tier_id, event_id, tier_name, badge, price_tnd, total_capacity, description, idx))

                created_tiers.append({
                    "id": tier_id,
                    "name": tier_name,
                    "badge": badge,
                    "price_tnd": price_tnd,
                    "total_capacity": total_capacity,
                    "sold_count": 0,
                    "description": description
                })

            # 3. Insert optional initial sellers
            created_sellers = []
            if isinstance(initial_sellers, list):
                for s in initial_sellers:
                    s_name = (s.get("name") or "").strip()
                    s_email = (s.get("email") or "").strip().lower()
                    s_phone = (s.get("phone") or "").strip()
                    if s_name and s_email:
                        s_id = f"slr-{os.urandom(4).hex()}"
                        cur.execute("""
                            INSERT INTO sellers (id, event_id, name, email, phone, status)
                            VALUES (%s, %s, %s, %s, %s, 'ACTIVE')
                            ON CONFLICT (event_id, email) DO UPDATE SET name = EXCLUDED.name, phone = EXCLUDED.phone;
                        """, (s_id, event_id, s_name, s_email, s_phone))
                        created_sellers.append({
                            "id": s_id,
                            "name": s_name,
                            "email": s_email,
                            "phone": s_phone,
                            "status": "ACTIVE",
                            "login_credentials": {
                                "email": s_email,
                                "event_pin": pin_code,
                                "auth_method": "Enter registered Email + 6-digit Event PIN to access Seller POS"
                            }
                        })

            conn.commit()

            return make_json_response({
                "status": "EVENT_CREATED",
                "message": "Event, ticket tiers, payment gateways, and seller accounts provisioned atomically in Cloud SQL.",
                "event": {
                    "id": event_id,
                    "title": title,
                    "slug": slug,
                    "venue": venue,
                    "city": city,
                    "date": date,
                    "time": time,
                    "pin_code": pin_code,
                    "enabled_gateways": enabled_gateways,
                    "cover_images": cover_images,
                    "banner_url": banner_url,
                    "tiers": created_tiers,
                    "sellers": created_sellers,
                    "checkout_url": f"https://eventpass.tn/e/{slug}",
                    "gate_pairing": {
                        "pin_code": pin_code,
                        "qr_pairing_data": f"EVENTPASS:PAIR:{event_id}:{pin_code}"
                    }
                }
            }, 201)

    except Exception as e:
        logger.error(f"Error in create_event: {e}")
        return make_json_response({"error": str(e)}, 500)


